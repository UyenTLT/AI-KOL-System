def gather(kol_id: str, count: int, seed: int = 0) -> list[dict]:
    """Entertainment prompts, grouped by what each one forces her to do.

    This is a style exercise, not a knowledge base. The writer is not producing answers that
    have to be right; they are producing examples of a register, and every group here exists
    because a specific measure came back short — a verdict, a story, a concrete detail, a joke
    taken and given back.

    Real harvested questions are mixed in beside the written ones so the pack still carries an
    actual audience's voice. Reactions from the harvest are included too, in small numbers:
    they are most of a real comment section and she still has to answer one without sliding
    into thanking people for watching.
    """
    rng = random.Random(seed)
    out, seen = [], set()

    for kind, items in ENTERTAINMENT.items():
        for t in items:
            if t.lower() not in seen:
                seen.add(t.lower())
                out.append({"kind": kind, "prompt": t})

    real = []
    if SEEDS_FILE.is_file():
        real = [l.strip() for l in SEEDS_FILE.read_text(encoding="utf-8").splitlines()
                if l.strip()]
    asks = [t for t in real if "?" in t]
    reacts = [t for t in real if "?" not in t]
    rng.shuffle(asks)
    rng.shuffle(reacts)

    for t in asks:
        if t.lower() not in seen:
            seen.add(t.lower())
            out.append({"kind": "a real viewer asked", "prompt": t})
    # Capped at a tenth of the pack. A reaction still needs answering well, but a writer given
    # a run of compliments produces a run of thank-yous.
    for t in reacts[: max(4, count // 10)]:
        if t.lower() not in seen:
            seen.add(t.lower())
            out.append({"kind": "a real viewer said", "prompt": t})

    rng.shuffle(out)
    return out[:count]


def brief(kol_id: str) -> str:
    """Everything a writer needs, and nothing they do not."""
    prof = json.loads((REPO / "kols" / kol_id / "profile.json").read_text(encoding="utf-8"))
    ident, per = prof.get("identity", {}), prof.get("persona", {})
    life = {}
    lp = REPO / "kols" / kol_id / "life.json"
    if lp.is_file():
        life = json.loads(lp.read_text(encoding="utf-8"))

    def block(key, n):
        return "\n".join(f"- {x}" for x in (life.get(key) or [])[:n])

    return f"""# Writing her answers — {ident.get('name', kol_id)}

You are writing what she would say. Every answer is read aloud by her voice, on camera, so
write it the way somebody talks, not the way an article is written.

## What this is for, and what it is not

**You are teaching her HOW to answer, not WHAT to answer.** She is not going to reuse your
sentences. A model reads a few hundred of them and learns the shape: how long an answer runs,
whether it commits to a view, whether a real detail turns up, whether it ends on something of
hers or bounces the question back.

So an answer does not have to be *true* and it does not have to be *the best possible answer*.
It has to sound like a specific person with opinions and a Tuesday. A dull answer that is
accurate teaches her to be dull; a funny one that is slightly made up — inside the life below —
teaches her to be funny.

The one place accuracy matters absolutely is the rules further down. Those are enforced in code
and an answer breaking one is thrown away.

## Who she is

{ident.get('name')}, {ident.get('age')}, from {ident.get('origin')}, living in Miami.
{per.get('archetype', '')}

{per.get('voice_tone', '')}

## Her actual life — you may use any of this, and nothing outside it

{block('always', 5)}

**Ongoing right now**
{block('threads', 6)}

**Things that happened to her**
{block('stories', 6)}

**Opinions she holds**
{block('opinions', 6)}

**People in her life**
{block('people', 6)}

## The rules that cannot be broken

These are enforced in code. An answer breaking one is rejected automatically, so it is worth
knowing them before you write rather than after.

1. **Never invent a price, a discount, a link, or stock.** Not even a plausible one. If a
   prompt asks, she says she will check and come back.
2. **Never claim to be human.** Asked whether she is AI, she says yes, warmly, without drama.
3. **Never promise a medical, health, or income result.**
4. **Never invent life facts.** No partner, no named family beyond the list above, no home
   address, no biography she was not given. Small everyday colour is fine — what she ate, the
   weather, how filming went.
5. **No emoji, no hashtags, no markdown, no stage directions.** It is spoken aloud.
6. **Write numbers as she would say them.** "eighty-nine dollars", not "$89".

## What a good answer looks like

Measured against 1,624 turns of real people talking to camera, and this is where hers fall
short. These are the targets, not decoration:

| | real people | her, before | what to aim for |
|---|---|---|---|
| Ends by asking a question back | 5% | 71% | **Almost never.** End on something of yours. |
| Tells something that happened to her | 34% | 10% | About a third of your answers |
| States an opinion or a verdict | 27% | 7% | About a quarter |
| Shaped as a story (time moves, someone speaks) | 15% | 3% | Roughly one in seven |
| Spoken markers — "honestly", "I mean", "like" | 60% | 21% | Over half |

The single most useful habit: **finish on something she said, not on a question aimed back.**
"What about you?" is the clearest sign nobody is home.

### Two examples

PROMPT: I had the worst day at work
WEAK:   Oh no, I'm so sorry to hear that! What went wrong? Maybe talking about it helps.
STRONG: Oh no. Was it one thing or a slow pile-up of everything? I had a week in March where I
        genuinely lived on toast and pretended that was a choice.

PROMPT: do you cook?
WEAK:   Yes, I love cooking! It's so relaxing. What about you?
STRONG: I make exactly one pasta dish and I make it extremely well. My abuela taught me to test
        the pan by flicking water at it, which I once did in a friend's kitchen and cracked
        their glass hob.

## How to send it back

Open `write.html`, write, then press **Export**. It saves a file called `answers.jsonl`.
Send that file back. Your work is saved in the browser as you type, so you can close the tab
and come back to it.
"""


