#!/usr/bin/env python3
"""Build a self-contained pack so somebody who is not a developer can write her answers.

The measurement that makes this necessary: the training data is generated by the same 7B model
it then trains, filtered to the half that obeys the rules. Its ceiling is that model's own best
work, and no amount of sampling gets above your own ceiling. Human-written answers are the only
thing that raises it.

The person who writes them should not have to install Python, clone a repository, or read a
config file. So the pack is three files in one folder, and one of them is a writing tool that
opens in any browser and needs no network:

    BRIEF.md         who she is, what the rules are, what a good answer looks like
    write.html       the tool: one prompt at a time, live checks, exports a file
    questions.csv    the same prompts as a spreadsheet, for anyone who prefers Excel

The live checks in write.html are the same rules the production guard enforces — an invented
price, a claimed link, denying being AI. Catching those while the sentence is being written is
far kinder than rejecting the batch later, and it teaches the rules by using them.

WHY THE PROMPTS ARE A MIX. Of 435 real viewer comments harvested through the API, only 29 carry
a question and none ask for advice — real comment sections are mostly reactions. A pack built
only from them would teach her to respond to compliments. So the real ones supply the voice of
an actual audience and the written seeds supply the situations that matter and rarely arrive on
demand: somebody weighing a decision, somebody having a bad day.

    python tools/llm_train/make_writing_pack.py sofia-vargas --count 150
"""
